// Writes src/data/currencyNames.ts: English, Ukrainian, Polish and German names for every ISO 4217 code
// that Node's full ICU knows. Android WebViews ship trimmed ICU data and miss many of these.
// Run: node tools/gen-currency-names.cjs
const fs = require('fs');
const path = require('path');
const codes = Intl.supportedValuesOf('currency');
const out = { en: {}, uk: {}, pl: {}, de: {} };
for (const lang of ['en', 'uk', 'pl', 'de']) {
  const dn = new Intl.DisplayNames([lang], { type: 'currency', fallback: 'none' });
  for (const code of codes) {
    const name = dn.of(code);
    if (name && name.toUpperCase() !== code) {
      out[lang][code] = lang === 'en' ? name : name.charAt(0).toLocaleUpperCase(lang) + name.slice(1);
    }
  }
}
const body = (o) => Object.entries(o).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n');
const ts = `// Generated by tools/gen-currency-names.cjs. Do not edit by hand.
// Phones' WebViews often lack these names, so the app ships its own copy.
export const CURRENCY_NAMES: Record<'en' | 'uk' | 'pl' | 'de', Record<string, string>> = {
  en: {
${body(out.en).replace(/^/gm, '  ')}
  },
  uk: {
${body(out.uk).replace(/^/gm, '  ')}
  },
  pl: {
${body(out.pl).replace(/^/gm, '  ')}
  },
  de: {
${body(out.de).replace(/^/gm, '  ')}
  },
};
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'currencyNames.ts'), ts);
console.log('en', Object.keys(out.en).length, 'uk', Object.keys(out.uk).length, 'pl', Object.keys(out.pl).length, 'de', Object.keys(out.de).length);
