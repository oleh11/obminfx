const fs = require('fs');

const converterTabContent = [
  'import React, { useState } from "react";',
  'import { ',
  '  ArrowRightLeft, Plus, Trash2, Check, Copy, ',
  '  TrendingUp, Percent, Sparkles, Globe ',
  '} from "lucide-react";',
  'import { ExchangeRateData } from "../types/currency";',
  'import { getCurrencyMeta } from "../data/currencies";',
  'import { RateService } from "../services/rateService";',
  'import { formatCurrencyAmount, calculateBankFeeConversion } from "../services/feeCalculator";',
  'import { StorageService } from "../services/storageService";',
  '',
  'interface ConverterTabProps {',
  '  baseCurrency: string;',
  '  onSelectBaseCurrency: (code: string) => void;',
  '  baseAmount: string;',
  '  onAmountChange: (amount: string) => void;',
  '  pinnedCurrencies: string[];',
  '  onRemovePinnedCurrency: (code: string) => void;',
  '  onOpenAddModal: () => void;',
  '  onOpenSourceModal: () => void;',
  '  rateData: ExchangeRateData | null;',
  '  bankFeePct: number;',
  '  onBankFeeChange: (fee: number) => void;',
  '  onNavigateToFeeCalc: () => void;',
  '  onNavigateToTrends: (from: string, to: string) => void;',
  '}',
  '',
  'export const ConverterTab: React.FC<ConverterTabProps> = ({',
  '  baseCurrency,',
  '  onSelectBaseCurrency,',
  '  baseAmount,',
  '  onAmountChange,',
  '  pinnedCurrencies,',
  '  onRemovePinnedCurrency,',
  '  onOpenAddModal,',
  '  onOpenSourceModal,',
  '  rateData,',
  '  bankFeePct,',
  '  onBankFeeChange,',
  '  onNavigateToFeeCalc,',
  '  onNavigateToTrends',
  '}) => {',
  '  const [copiedCode, setCopiedCode] = useState<string | null>(null);',
  '  const [showFeeConfig, setShowFeeConfig] = useState<boolean>(false);',
  '',
  '  const baseMeta = getCurrencyMeta(baseCurrency);',
  '  const numericAmount = parseFloat(baseAmount) || 0;',
  '',
  '  const handleCopyAmount = (code: string, formattedAmount: string) => {',
  '    StorageService.triggerHaptic();',
  '    navigator.clipboard.writeText(formattedAmount.replace(/,/g, ""));',
  '    setCopiedCode(code);',
  '    setTimeout(() => setCopiedCode(null), 2000);',
  '  };',
  '',
  '  return (',
  '    <div className="space-y-4 max-w-md mx-auto pb-8">',
  '      {/* Primary Base Currency Input Card */}',
  '      <div className="p-5 rounded-3xl bg-slate-900 border border-slate-800 shadow-2xl relative overflow-hidden transition-all">',
  '        <div className="absolute top-0 right-0 w-48 h-48 bg-gradient-to-bl from-blue-600/10 via-indigo-500/10 to-transparent rounded-full blur-2xl pointer-events-none" />',
  '',
  '        {/* Currency Picker Button & Bank Fee Pill */}',
  '        <div className="flex items-center justify-between gap-2 mb-4">',
  '          <button',
  '            onClick={() => {',
  '              StorageService.triggerHaptic();',
  '              onOpenAddModal();',
  '            }}',
  '            className="flex items-center gap-2.5 px-3.5 py-2 rounded-2xl bg-slate-800/90 hover:bg-slate-750 active:scale-98 border border-slate-700 text-white transition-all shadow-sm"',
  '          >',
  '            <span className="text-2xl">{baseMeta.flag}</span>',
  '            <div className="text-left">',
  '              <div className="flex items-center gap-1">',
  '                <span className="font-extrabold text-base tracking-tight text-white">{baseMeta.code}</span>',
  '                <ArrowRightLeft className="w-3.5 h-3.5 text-slate-400" />',
  '              </div>',
  '              <span className="text-[11px] text-slate-300 font-medium block truncate max-w-[110px]">',
  '                {baseMeta.country}',
  '              </span>',
  '            </div>',
  '          </button>',
  '',
  '          {/* Fee Pill */}',
  '          <button',
  '            onClick={() => {',
  '              StorageService.triggerHaptic();',
  '              setShowFeeConfig(!showFeeConfig);',
  '            }}',
  '            className={"flex items-center gap-1.5 px-3 py-1.5 rounded-full text-xs font-bold transition-all border " + (bankFeePct > 0 ? "bg-amber-500/15 text-amber-300 border-amber-500/30 shadow-sm" : "bg-emerald-500/15 text-emerald-300 border-emerald-500/30")}',
  '          >',
  '            <Percent className="w-3.5 h-3.5" />',
  '            <span>{bankFeePct > 0 ? bankFeePct + "% Bank Fee" : "0% No Fee"}</span>',
  '          </button>',
  '        </div>',
  '',
  '        {/* Number Input (Full Keyboard Support) */}',
  '        <div className="relative my-2">',
  '          <div className="flex items-baseline justify-end gap-2 bg-slate-950/70 border border-slate-800 rounded-2xl px-4 py-3 focus-within:ring-2 focus-within:ring-blue-500 focus-within:border-transparent transition-all">',
  '            <span className="text-slate-400 font-extrabold text-2xl select-none">',
  '              {baseMeta.symbol}',
  '            </span>',
  '            <input',
  '              type="number"',
  '              inputMode="decimal"',
  '              step="any"',
  '              value={baseAmount}',
  '              onChange={(e) => onAmountChange(e.target.value)}',
  '              placeholder="0.00"',
  '              className="w-full bg-transparent text-right font-mono font-black text-4xl text-white placeholder-slate-600 focus:outline-none tracking-tight"',
  '            />',
  '          </div>',
  '          <p className="text-right text-xs text-slate-400 font-medium mt-1.5 mr-1">',
  '            {baseMeta.name}',
  '          </p>',
  '        </div>',
  '',
  '        {/* Collapsible Quick Bank Fee Presets */}',
  '        {showFeeConfig && (',
  '          <div className="mt-4 pt-3.5 border-t border-slate-800/80 animate-fade-in space-y-2">',
  '            <div className="flex items-center justify-between">',
  '              <span className="text-xs font-bold uppercase tracking-wider text-slate-400">',
  '                Bank Foreign Spread Fee:',
  '              </span>',
  '              <button',
  '                onClick={onNavigateToFeeCalc}',
  '                className="text-xs font-semibold text-blue-400 hover:text-blue-300 flex items-center gap-1"',
  '              >',
  '                <span>Full Calculator</span> &rarr;',
  '              </button>',
  '            </div>',
  '            ',
  '            <div className="grid grid-cols-4 gap-1.5">',
  '              {[0, 1.0, 2.0, 3.0].map((fee) => {',
  '                const isSelected = Math.abs(bankFeePct - fee) < 0.05;',
  '                return (',
  '                  <button',
  '                    key={fee}',
  '                    onClick={() => {',
  '                      StorageService.triggerHaptic();',
  '                      onBankFeeChange(fee);',
  '                    }}',
  '                    className={"py-2 rounded-xl text-xs font-extrabold border transition-all " + (isSelected ? "bg-amber-500/20 text-amber-300 border-amber-500 shadow-md ring-1 ring-amber-500/40" : "bg-slate-800/80 text-slate-300 border-slate-700 hover:bg-slate-800")}',
  '                  >',
  '                    {fee === 0 ? "0% Free" : fee === 2.0 ? "2% Avg" : fee + "%"}',
  '                  </button>',
  '                );',
  '              })}',
  '            </div>',
  '          </div>',
  '        )}',
  '      </div>',
  '',
  '      {/* Watchlist / Live Conversions Header */}',
  '      <div className="flex items-center justify-between px-2 pt-1">',
  '        <div className="flex items-center gap-2">',
  '          <span className="text-xs font-black uppercase tracking-wider text-slate-300">',
  '            Live Conversions',
  '          </span>',
  '          <span className="text-[11px] px-2 py-0.5 rounded-full bg-slate-800 font-bold text-slate-400">',
  '            {pinnedCurrencies.filter(c => c !== baseCurrency).length} active',
  '          </span>',
  '        </div>',
  '',
  '        <button',
  '          onClick={() => {',
  '            StorageService.triggerHaptic();',
  '            onOpenAddModal();',
  '          }}',
  '          className="flex items-center gap-1.5 px-3 py-1.5 rounded-full bg-blue-600 hover:bg-blue-500 active:scale-95 text-white text-xs font-bold transition-all shadow-md shadow-blue-600/20"',
  '        >',
  '          <Plus className="w-3.5 h-3.5" />',
  '          <span>Add Currency</span>',
  '        </button>',
  '      </div>',
  '',
  '      {/* Converted Currencies List */}',
  '      <div className="space-y-3">',
  '        {pinnedCurrencies',
  '          .filter(code => code !== baseCurrency)',
  '          .map((code) => {',
  '            const meta = getCurrencyMeta(code);',
  '            const rawRate = rateData ? RateService.calculateRate(baseCurrency, code, rateData) : 1.0;',
  '',
  '            const feeCalc = calculateBankFeeConversion(',
  '              numericAmount,',
  '              baseCurrency,',
  '              code,',
  '              rawRate,',
  '              bankFeePct',
  '            );',
  '',
  '            const formattedTotal = formatCurrencyAmount(feeCalc.totalBilledAmount, meta.decimalPlaces);',
  '            const formattedFee = formatCurrencyAmount(feeCalc.bankFeeAmount, meta.decimalPlaces);',
  '            const isCopied = copiedCode === code;',
  '',
  '            return (',
  '              <div',
  '                key={code}',
  '                className="p-4 rounded-3xl bg-slate-900 border border-slate-800 hover:border-slate-700 shadow-xl transition-all relative overflow-hidden"',
  '              >',
  '                {/* Header: Flag, Currency Code & Delete */}',
  '                <div className="flex items-start justify-between">',
  '                  <div className="flex items-center gap-3">',
  '                    <span className="text-3xl leading-none">{meta.flag}</span>',
  '                    <div>',
  '                      <div className="flex items-center gap-1.5">',
  '                        <span className="font-extrabold text-lg text-white tracking-tight">{meta.code}</span>',
  '                        <span className="text-xs text-slate-400 font-mono font-medium">({meta.symbol})</span>',
  '                      </div>',
  '                      <p className="text-xs text-slate-400 font-medium">{meta.name}</p>',
  '                    </div>',
  '                  </div>',
  '',
  '                  <button',
  '                    onClick={() => {',
  '                      StorageService.triggerHaptic();',
  '                      onRemovePinnedCurrency(code);',
  '                    }}',
  '                    className="p-1.5 rounded-full text-slate-500 hover:text-rose-400 hover:bg-rose-500/10 transition-colors"',
  '                    title="Remove from list"',
  '                  >',
  '                    <Trash2 className="w-4 h-4" />',
  '                  </button>',
  '                </div>',
  '',
  '                {/* Amount display */}',
  '                <div className="my-3 text-right">',
  '                  <div className="flex items-baseline justify-end gap-1.5">',
  '                    <span className="font-mono font-black text-3xl text-white tracking-tight">',
  '                      {formattedTotal}',
  '                    </span>',
  '                    <span className="text-base font-extrabold text-slate-400">',
  '                      {meta.symbol}',
  '                    </span>',
  '                  </div>',
  '',
  '                  {bankFeePct > 0 && (',
  '                    <p className="text-xs font-semibold text-amber-400 mt-1">',
  '                      Includes +{formattedFee} {meta.symbol} ({bankFeePct}%) bank fee',
  '                    </p>',
  '                  )}',
  '                </div>',
  '',
  '                {/* Footer: Live Rate + Action Buttons */}',
  '                <div className="pt-3 border-t border-slate-800/80 flex items-center justify-between text-xs">',
  '                  <span className="font-mono text-slate-400 text-[11px]">',
  '                    1 {baseMeta.code} = {rawRate < 0.01 ? rawRate.toFixed(6) : rawRate.toFixed(4)} {meta.code}',
  '                  </span>',
  '',
  '                  <div className="flex items-center gap-2">',
  '                    <button',
  '                      onClick={() => handleCopyAmount(code, formattedTotal)}',
  '                      className={"flex items-center gap-1 px-2.5 py-1 rounded-xl font-bold text-xs transition-all " + (isCopied ? "bg-emerald-500/20 text-emerald-300 border border-emerald-500/30" : "bg-slate-800 hover:bg-slate-700 text-slate-300 border border-slate-700")}',
  '                    >',
  '                      {isCopied ? (',
  '                        <>',
  '                          <Check className="w-3.5 h-3.5 text-emerald-400" />',
  '                          <span>Copied</span>',
  '                        </>',
  '                      ) : (',
  '                        <>',
  '                          <Copy className="w-3.5 h-3.5" />',
  '                          <span>Copy</span>',
  '                        </>',
  '                      )}',
  '                    </button>',
  '',
  '                    <button',
  '                      onClick={() => {',
  '                        StorageService.triggerHaptic();',
  '                        onNavigateToTrends(baseCurrency, code);',
  '                      }}',
  '                      className="p-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-300 border border-slate-700 transition-colors"',
  '                      title="View historical trend chart"',
  '                    >',
  '                      <TrendingUp className="w-3.5 h-3.5 text-blue-400" />',
  '                    </button>',
  '                  </div>',
  '                </div>',
  '              </div>',
  '            );',
  '          })}',
  '      </div>',
  '    </div>',
  '  );',
  '};'
].join('\n');

fs.writeFileSync('src/components/ConverterTab.tsx', converterTabContent, 'utf8');
